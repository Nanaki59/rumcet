// src/shared/mameVersion.ts
// Comparaison des versions MAME (ex. chdman "0.288"), partagée main / renderer.

/** Compare deux versions MAME ("0.288" < "0.290"). Une version inconnue est la plus ancienne. */
export function compareMameVersions(a: string | null, b: string | null): number {
  if (a === b) return 0;
  if (!a) return -1;
  if (!b) return 1;
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const diff = (pa[i] || 0) - (pb[i] || 0);
    if (diff !== 0) return diff;
  }
  return 0;
}
